CREATE TABLE phone_verification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES user_account(id),
    phone_number VARCHAR(20) NOT NULL,
    code_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5)
);

CREATE TABLE phone_verification_send_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id),
    phone_number VARCHAR(20) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_phone_send_attempt_user_time
    ON phone_verification_send_attempt(user_id, requested_at);
CREATE INDEX idx_phone_send_attempt_number_time
    ON phone_verification_send_attempt(phone_number, requested_at);
