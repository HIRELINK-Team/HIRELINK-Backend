CREATE TABLE term_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_type_name VARCHAR(50) NOT NULL,
    CONSTRAINT uk_term_type_name UNIQUE (term_type_name)
);

CREATE TABLE user_term_agreement (
    user_id BIGINT NOT NULL,
    term_type_id BIGINT NOT NULL,
    is_agreed BOOLEAN NOT NULL,
    agreed_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, term_type_id),
    CONSTRAINT fk_user_term_agreement_user FOREIGN KEY (user_id) REFERENCES user_account(id),
    CONSTRAINT fk_user_term_agreement_term FOREIGN KEY (term_type_id) REFERENCES term_type(id)
);

