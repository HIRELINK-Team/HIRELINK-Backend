CREATE TABLE visa_type (
    visa_code VARCHAR(20) PRIMARY KEY,
    visa_name VARCHAR(100) NOT NULL
);

CREATE TABLE study_program (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_study_program_name UNIQUE (program_name)
);

CREATE TABLE student_profile (
    id BIGINT PRIMARY KEY,
    birth_date DATE NOT NULL,
    nationality CHAR(2) NOT NULL,
    current_region VARCHAR(150) NOT NULL,
    korean_level VARCHAR(30) NOT NULL,
    visa_code VARCHAR(20),
    university_name VARCHAR(150),
    enrollment_start_date DATE,
    study_program_id BIGINT,
    grade_level SMALLINT,
    academic_state VARCHAR(30),
    topik_level SMALLINT,
    stay_start_date DATE,
    stay_expiration_date DATE,
    profile_image_key VARCHAR(500),
    certification_prompt_dismissed_at TIMESTAMPTZ,
    hirelink_badge_issued_at TIMESTAMPTZ,
    CONSTRAINT fk_student_profile_user FOREIGN KEY (id) REFERENCES user_account(id),
    CONSTRAINT fk_student_profile_visa FOREIGN KEY (visa_code) REFERENCES visa_type(visa_code),
    CONSTRAINT fk_student_profile_study_program FOREIGN KEY (study_program_id) REFERENCES study_program(id)
);
