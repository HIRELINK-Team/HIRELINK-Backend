CREATE TABLE developer_inquiry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_user_id BIGINT NOT NULL,
    user_role VARCHAR(20) NOT NULL,
    reply_email VARCHAR(255) NOT NULL,
    inquiry_type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_developer_inquiry_type_not_blank
        CHECK (btrim(inquiry_type) <> ''),
    CONSTRAINT ck_developer_inquiry_title_not_blank
        CHECK (btrim(title) <> ''),
    CONSTRAINT ck_developer_inquiry_content_not_blank
        CHECK (btrim(content) <> '')
);

CREATE INDEX ix_developer_inquiry_author_submitted
    ON developer_inquiry(author_user_id, submitted_at DESC);
