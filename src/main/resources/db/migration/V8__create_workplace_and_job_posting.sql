CREATE TABLE business_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT uk_business_type_name UNIQUE (name)
);

CREATE TABLE workplace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_user_id BIGINT NOT NULL,
    workplace_name VARCHAR(150) NOT NULL,
    representative_name VARCHAR(100) NOT NULL,
    business_registration_file_key VARCHAR(500) NOT NULL,
    business_registration_number VARCHAR(20) NOT NULL,
    business_type_id BIGINT NOT NULL,
    workplace_address VARCHAR(500) NOT NULL,
    latitude NUMERIC(10,7) NOT NULL,
    longitude NUMERIC(10,7) NOT NULL,
    employee_count_range VARCHAR(20) NOT NULL,
    CONSTRAINT uk_workplace_business_registration_number UNIQUE (business_registration_number),
    CONSTRAINT fk_workplace_employer FOREIGN KEY (employer_user_id) REFERENCES user_account(id),
    CONSTRAINT fk_workplace_business_type FOREIGN KEY (business_type_id) REFERENCES business_type(id)
);

CREATE TABLE job_posting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workplace_id BIGINT NOT NULL,
    business_type_id BIGINT,
    other_job_name VARCHAR(100),
    title VARCHAR(200),
    job_role VARCHAR(100),
    wage_type VARCHAR(20),
    wage_amount INTEGER,
    status VARCHAR(20) NOT NULL,
    recruitment_count SMALLINT,
    work_start_date DATE,
    required_korean_level VARCHAR(30),
    preferred_experience VARCHAR(30),
    work_time_negotiable BOOLEAN,
    application_deadline_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ,
    CONSTRAINT fk_job_posting_workplace FOREIGN KEY (workplace_id) REFERENCES workplace(id),
    CONSTRAINT fk_job_posting_business_type FOREIGN KEY (business_type_id) REFERENCES business_type(id)
);
