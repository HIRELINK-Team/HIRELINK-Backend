CREATE TABLE recommendation_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_profile_id BIGINT NOT NULL,
    algorithm_version VARCHAR(30) NOT NULL,
    input_snapshot JSONB NOT NULL,
    invalidated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_recommendation_batch_student_profile
        FOREIGN KEY (student_profile_id) REFERENCES student_profile(id)
);

CREATE TABLE recommendation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    job_posting_id BIGINT NOT NULL,
    rank SMALLINT NOT NULL,
    score NUMERIC(5,2) NOT NULL,
    reason_json JSONB,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_recommendation_batch
        FOREIGN KEY (batch_id) REFERENCES recommendation_batch(id),
    CONSTRAINT fk_recommendation_job_posting
        FOREIGN KEY (job_posting_id) REFERENCES job_posting(id),
    CONSTRAINT uk_recommendation_batch_rank UNIQUE (batch_id, rank),
    CONSTRAINT uk_recommendation_batch_job_posting UNIQUE (batch_id, job_posting_id),
    CONSTRAINT ck_recommendation_rank CHECK (rank BETWEEN 1 AND 3)
);

CREATE TABLE application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id BIGINT NOT NULL,
    student_profile_id BIGINT NOT NULL,
    job_posting_id BIGINT NOT NULL,
    desired_start_date DATE NOT NULL,
    snapshot_version SMALLINT NOT NULL,
    application_snapshot JSONB NOT NULL,
    status VARCHAR(30) NOT NULL,
    end_reason VARCHAR(50),
    employer_response_deadline TIMESTAMPTZ NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    CONSTRAINT fk_application_recommendation
        FOREIGN KEY (recommendation_id) REFERENCES recommendation(id),
    CONSTRAINT fk_application_student_profile
        FOREIGN KEY (student_profile_id) REFERENCES student_profile(id),
    CONSTRAINT fk_application_job_posting
        FOREIGN KEY (job_posting_id) REFERENCES job_posting(id),
    CONSTRAINT uk_application_recommendation UNIQUE (recommendation_id),
    CONSTRAINT uk_application_student_job_posting UNIQUE (student_profile_id, job_posting_id),
    CONSTRAINT ck_application_status
        CHECK (status IN ('WAITING_RESPONSE', 'OFFERED', 'COMPLETED', 'ENDED')),
    CONSTRAINT ck_application_end_reason
        CHECK (end_reason IS NULL OR end_reason IN (
            'EMPLOYER_REJECTED',
            'WITHDRAWN',
            'EMPLOYER_RESPONSE_EXPIRED',
            'STUDENT_REJECTED',
            'STUDENT_RESPONSE_EXPIRED',
            'JOB_POSTING_CLOSED'
        ))
);

CREATE TABLE employment_offer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    end_reason VARCHAR(50),
    student_response_deadline TIMESTAMPTZ NOT NULL,
    offered_at TIMESTAMPTZ NOT NULL,
    responded_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    CONSTRAINT fk_employment_offer_application
        FOREIGN KEY (application_id) REFERENCES application(id),
    CONSTRAINT uk_employment_offer_application UNIQUE (application_id),
    CONSTRAINT ck_employment_offer_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED')),
    CONSTRAINT ck_employment_offer_end_reason
        CHECK (end_reason IS NULL OR end_reason IN (
            'STUDENT_REJECTED',
            'STUDENT_RESPONSE_EXPIRED',
            'JOB_POSTING_CLOSED'
        ))
);

CREATE TABLE employment_match (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employment_offer_id BIGINT NOT NULL,
    completed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_employment_match_offer
        FOREIGN KEY (employment_offer_id) REFERENCES employment_offer(id),
    CONSTRAINT uk_employment_match_offer UNIQUE (employment_offer_id)
);
