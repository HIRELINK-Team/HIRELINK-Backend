CREATE TABLE priority_criterion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criterion_name VARCHAR(50) NOT NULL,
    CONSTRAINT uk_priority_criterion_name UNIQUE (criterion_name)
);

CREATE TABLE student_preferred_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    business_type_id BIGINT NOT NULL,
    other_job_name VARCHAR(100),
    CONSTRAINT fk_student_preferred_job_profile FOREIGN KEY (user_id) REFERENCES student_profile(id),
    CONSTRAINT fk_student_preferred_job_business_type FOREIGN KEY (business_type_id) REFERENCES business_type(id)
);

CREATE TABLE student_preferred_work_time (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    day_of_week VARCHAR(10) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    CONSTRAINT fk_student_preferred_work_time_profile FOREIGN KEY (user_id) REFERENCES student_profile(id)
);

CREATE TABLE student_preferred_location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    location_name VARCHAR(150) NOT NULL,
    latitude NUMERIC(10,7) NOT NULL,
    longitude NUMERIC(10,7) NOT NULL,
    radius_m INTEGER NOT NULL,
    CONSTRAINT uk_student_preferred_location_user UNIQUE (user_id),
    CONSTRAINT fk_student_preferred_location_profile FOREIGN KEY (user_id) REFERENCES student_profile(id)
);

CREATE TABLE student_job_preference (
    user_id BIGINT PRIMARY KEY,
    minimum_hourly_wage INTEGER,
    business_type_flexible BOOLEAN NOT NULL,
    CONSTRAINT fk_student_job_preference_profile FOREIGN KEY (user_id) REFERENCES student_profile(id)
);

CREATE TABLE student_priority (
    user_id BIGINT NOT NULL,
    criterion_id BIGINT NOT NULL,
    priority_order SMALLINT NOT NULL,
    weight NUMERIC(6,3) NOT NULL,
    PRIMARY KEY (user_id, criterion_id),
    CONSTRAINT uk_student_priority_order UNIQUE (user_id, priority_order),
    CONSTRAINT fk_student_priority_profile FOREIGN KEY (user_id) REFERENCES student_profile(id),
    CONSTRAINT fk_student_priority_criterion FOREIGN KEY (criterion_id) REFERENCES priority_criterion(id)
);
