CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    role VARCHAR(20) NOT NULL,
    email VARCHAR(255) NOT NULL,
    email_verified_at TIMESTAMPTZ,
    phone_number VARCHAR(20),
    phone_verified_at TIMESTAMPTZ,
    acquisition_channel VARCHAR(50),
    preferred_language VARCHAR(10) NOT NULL DEFAULT 'KO',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    withdrawn_at TIMESTAMPTZ,
    CONSTRAINT uk_user_account_email UNIQUE (email),
    CONSTRAINT uk_user_account_phone_number UNIQUE (phone_number)
);

CREATE TABLE auth_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255),
    CONSTRAINT fk_auth_account_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT uk_auth_account_provider_user_id UNIQUE (provider, provider_user_id)
);
