CREATE TABLE student_career (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    career_name VARCHAR(150) NOT NULL,
    start_month CHAR(7) NOT NULL,
    end_month CHAR(7) NOT NULL,
    description TEXT,
    CONSTRAINT fk_student_career_profile FOREIGN KEY (user_id) REFERENCES student_profile(id)
);
